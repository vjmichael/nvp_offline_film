"""WO5 finished-DCP viewer: trusted native decoder binary admission.

The released NSIS app must embed an independently generated build-time SHA
of its sealed binary+license manifest. Until installer freeze supplies that
pin and the complete reviewed bundle, the finished-film decoder is disabled.

A developer may explicitly opt into local codec tests by supplying exact
executable paths AND precomputed SHA pins to the HOST environment. Neither
source can be selected through HTTP, JavaScript, AI tools or film projects.
"""
from __future__ import annotations
from hashlib import sha256
import json
import os
from pathlib import Path
import re
import sys

from backend.nvp_wo3_codec_bundle_provenance import verify_native_codec_bundle
from backend.nvp_wo3_native_codecs import ApprovedCodecBinary

# Generated by release packaging from the signed/reviewed codec manifest.
# Do NOT replace with a runtime-calculated hash; that would self-certify an
# attacker-modified codec folder. Release bundle remains a separate gate.
from backend._nvp_wo5_release_pin import RELEASE_CODEC_MANIFEST_SHA256
SHA=re.compile(r"[0-9a-f]{64}\Z")

def pinned_codec_pair(root,manifest,expected_manifest_sha256):
    if (type(manifest) is not dict or
            type(expected_manifest_sha256) is not str or
            SHA.fullmatch(expected_manifest_sha256) is None):
        raise PermissionError("Trusted native codec release manifest pin missing")
    canonical=json.dumps(manifest,sort_keys=True,
                         separators=(",",":"),ensure_ascii=True).encode("ascii")
    if sha256(canonical).hexdigest()!=expected_manifest_sha256:
        raise PermissionError("Installed decoder manifest differs from build pin")
    record=verify_native_codec_bundle(root,manifest)
    # Release alpha uses fully static reviewed tools. Reject unmanifested
    # DLLs/aliases/files rather than trusting a hash of the EXE while
    # Windows loads an unreviewed same-directory native dependency.
    allowed={"nvp-codec-manifest.json"}
    for entry in record["tools"].values():
        allowed.add(entry["filename"])
    for entry in manifest["tools"].values():
        allowed.add(entry["license_notice"])
    root=Path(root)
    if (set(path.name for path in root.iterdir())!=allowed or
            any(path.is_symlink() or not path.is_file()
                for path in root.iterdir())):
        raise PermissionError("Unreviewed native codec dependency or staged extra file")
    roles=record["tools"]
    root=Path(root).resolve(strict=True)
    result=[]
    for label,product in (
            ("asdcp-unwrap","ASDCP-asdcp_unwrap"),
            ("openjpeg-decoder","OpenJPEG-opj_decompress")):
        item=roles[label]
        result.append(ApprovedCodecBinary(
            root/item["filename"],sha256=item["binary_sha256"],
            product=product))
    return tuple(result)

def _developer_native_codecs():
    if os.environ.get("NVP_WO5_DEV_FINISHED_DECODER")!="explicit-local-only":
        return None
    keys=(
        ("NVP_NATIVE_ASDCP_UNWRAP","NVP_NATIVE_ASDCP_UNWRAP_SHA256",
         "ASDCP-asdcp_unwrap"),
        ("NVP_NATIVE_OPENJPEG_DECODE","NVP_NATIVE_OPENJPEG_DECODE_SHA256",
         "OpenJPEG-opj_decompress"))
    spec=[]
    for path_key,sha_key,product in keys:
        path=os.environ.get(path_key)
        digest=os.environ.get(sha_key)
        if (type(path) is not str or type(digest) is not str or
                SHA.fullmatch(digest) is None):
            return None
        file=Path(path)
        if not file.is_absolute() or file.is_symlink() or not file.is_file():
            return None
        spec.append((file,digest,product))
    def provider():
        return tuple(ApprovedCodecBinary(
            file,sha256=digest,product=product) for file,digest,product in spec)
    return provider

def desktop_finished_decoder_provider(bundle_root):
    """Create source-pinned installed provider; never import from project data."""
    if getattr(sys,"frozen",False):
        if not RELEASE_CODEC_MANIFEST_SHA256:
            return None
        root=Path(bundle_root)/"native-codecs"
        manifest_file=root/"nvp-codec-manifest.json"
        if (root.is_symlink() or manifest_file.is_symlink() or
                not manifest_file.is_file() or
                manifest_file.stat().st_size>128*1024):
            return None
        try:
            manifest=json.loads(manifest_file.read_text(encoding="utf8"))
        except (ValueError,OSError):
            return None
        return lambda:pinned_codec_pair(
            root,manifest,RELEASE_CODEC_MANIFEST_SHA256)
    return _developer_native_codecs()

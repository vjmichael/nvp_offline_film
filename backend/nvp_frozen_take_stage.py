"""NVP STACK-02C3B8: freeze FilmIndex Digital Take as exact native Blender inputs.

A frozen take is independent of today's editable WorldState/ShotSequence.
This host-only code never mints native creator approval or starts Blender.
All executable source is generated by NVP's existing trusted exporter from
independently re-opened, SHA-checked FilmIndex data.
"""
from __future__ import annotations

import copy
from hashlib import sha256
from pathlib import Path
import secrets
import shutil

from backend.nvp_blender_worker import BlenderOperation, BlenderWorkerSupervisor,sha_file
from backend.nvp_digital_capture import DigitalCapture
from backend.nvp_production_scene import compact, digest
from backend.nvp_render_source_stage import _write_exclusive
from backend.nvp_shot_sequence import FPS,actor_xy_at,animated_blender_script

FORMAT="nvp.production.staged_frozen_take.v1"
WORLD="frozen_world.json"
TIMED="frozen_timed_take.json"
SCRIPT="trusted_frozen_take.py"
BLEND="frozen_take.blend"


def _source(capture:DigitalCapture,project_id:str,take_id:str):
    """Reopen the actual indexed frozen revisions, never the mutable stage."""
    if not isinstance(capture,DigitalCapture):
        raise TypeError("Trusted DigitalCapture source required")
    frozen=capture.reopen(project_id,take_id)
    world=frozen["world"]
    timed=copy.deepcopy(frozen["timed_take"])
    if timed.get("fps")!=FPS or not timed.get("shots"):
        raise RuntimeError("Frozen Digital Take has no valid timeline")
    total=timed["shots"][-1]["stop_frame"]-1
    if type(total) is not int or not 1<=total<=FPS*60*10:
        raise RuntimeError("Frozen Digital Take frame extent unsafe")
    instances={x["instance_id"]:x for x in world["instances"]}
    for actor in timed["actors"]:
        instance=instances[actor["instance_id"]]
        marks=actor["marks"]
        samples={1,max(1,total//2),total}
        for move in marks:
            a=move["mark"]
            for second in (a["start_s"],(a["start_s"]+a["end_s"])/2,a["end_s"]):
                samples.add(max(1,min(total,1+round(second*FPS))))
        actor["audit_samples"]=[
            {"frame":frame,
             "xy":actor_xy_at(instance,marks,(frame-1)/FPS)}
            for frame in sorted(samples)]
    script=animated_blender_script(world,timed)
    encoded={
        WORLD:compact(world).encode("utf8"),
        TIMED:compact(timed).encode("utf8"),
        SCRIPT:script.encode("utf8"),
    }
    if (any(not contents or len(contents)>4*1024*1024 for contents in encoded.values()) or
        digest(world)!=frozen["audit"]["world_sha256"]):
        raise RuntimeError("Frozen Digital Take source exceeds native audit bounds")
    return {
        "project_id":project_id,"take_id":take_id,
        "scene_id":frozen["record"]["data"]["scene_id"],
        "capture_sha256":frozen["record"]["document_sha256"],
        "world_sha256":frozen["audit"]["world_sha256"],
        "timed_source_sha256":frozen["audit"]["timed_sha256"],
        "timed_render_sha256":digest(timed),
        "frame_count":total,"frame_rate":FPS,
        "shot_count":len(timed["shots"]),
        "actor_count":len(timed["actors"]),
        "script_sha256":sha256(encoded[SCRIPT]).hexdigest(),
        "bytes":encoded,
    }


def stage_frozen_take(capture:DigitalCapture,supervisor:BlenderWorkerSupervisor,
                      project_id:str,take_id:str,*,ram_mb=2048,gpu_mb=0,
                      device_id=None,timeout_seconds=240,strict_linux_cgroup=False):
    if not isinstance(supervisor,BlenderWorkerSupervisor):
        raise TypeError("Established native Blender supervisor required")
    if type(ram_mb) is not int or not 256<=ram_mb<=65536:
        raise ValueError("Invalid native Blender RAM budget")
    if type(gpu_mb) is not int or not 0<=gpu_mb<=65536:
        raise ValueError("Invalid native Blender GPU budget")
    if gpu_mb and (not isinstance(device_id,str) or not device_id):
        raise ValueError("GPU ticket requires native device identity")
    if type(timeout_seconds) is not int or not 1<=timeout_seconds<=600:
        raise ValueError("Invalid native operation time limit")
    if type(strict_linux_cgroup) is not bool:
        raise ValueError("Strict containment setting must be boolean")
    initial=_source(capture,project_id,take_id)
    root=supervisor.root
    if not root.is_dir() or root.is_symlink() or root.resolve()!=root:
        raise RuntimeError("Unsafe native Blender workspace")
    job_id="frozen_"+secrets.token_hex(16)
    jobdir=root/job_id
    jobdir.mkdir(mode=0o700,exist_ok=False)
    try:
        for name,content in initial["bytes"].items():
            _write_exclusive(jobdir,name,content)
        operation=BlenderOperation(
            job_id=job_id,script=SCRIPT,
            script_sha256=initial["script_sha256"],
            inputs={WORLD:sha256(initial["bytes"][WORLD]).hexdigest(),
                    TIMED:initial["timed_render_sha256"]},
            outputs={BLEND:"blend"},arguments={"--output":BLEND},
            memory_limit_mb=ram_mb,gpu_memory_mb=gpu_mb,
            gpu_device_id=device_id,timeout_seconds=timeout_seconds,
            require_linux_cgroup_v2=strict_linux_cgroup,
        )
        supervisor._validate(operation)
        again=_source(capture,project_id,take_id)
        for field in ("capture_sha256","world_sha256","timed_source_sha256",
                      "timed_render_sha256","script_sha256","frame_count"):
            if initial[field]!=again[field]:
                raise RuntimeError("Frozen FilmIndex source changed while staging native replay")
        return {
            "format":FORMAT,"project_id":project_id,"scene_id":initial["scene_id"],
            "take_id":take_id,"capture_sha256":initial["capture_sha256"],
            "world_sha256":initial["world_sha256"],
            "timed_source_sha256":initial["timed_source_sha256"],
            "timed_render_sha256":initial["timed_render_sha256"],
            "script_sha256":initial["script_sha256"],
            "frame_count":initial["frame_count"],"frame_rate":initial["frame_rate"],
            "shot_count":initial["shot_count"],"actor_count":initial["actor_count"],
            "operation":operation,"stage_dir":jobdir,
            "native_approval":"not_granted","resource_admission":"not_checked",
            "execution":"not_started",
        }
    except BaseException:
        shutil.rmtree(jobdir)
        raise


def verify_frozen_stage(capture:DigitalCapture,supervisor:BlenderWorkerSupervisor,
                        staged:dict)->bool:
    """Recompute from original immutable FilmIndex sources, fail closed."""
    if (not isinstance(staged,dict) or staged.get("format")!=FORMAT or
        staged.get("native_approval")!="not_granted" or
        staged.get("execution")!="not_started" or
        staged.get("resource_admission")!="not_checked"):
        raise PermissionError("No exact inert frozen-take stage is available")
    op=staged.get("operation")
    if not isinstance(op,BlenderOperation):
        raise TypeError("Frozen take needs existing typed Blender operation")
    if staged.get("stage_dir")!=supervisor.root/op.job_id:
        raise PermissionError("Staged take does not belong to native worker")
    expected=_source(capture,staged["project_id"],staged["take_id"])
    for field in ("project_id","scene_id","take_id","capture_sha256","world_sha256",
                  "timed_source_sha256","timed_render_sha256","script_sha256",
                  "frame_count","frame_rate","shot_count","actor_count"):
        if staged.get(field)!=expected[field]:
            raise RuntimeError("Frozen take lineage or timing differs from indexed source")
    if (op.script!=SCRIPT or op.script_sha256!=expected["script_sha256"] or
        op.inputs!={WORLD:sha256(expected["bytes"][WORLD]).hexdigest(),
                    TIMED:expected["timed_render_sha256"]} or
        op.outputs!={BLEND:"blend"} or
        op.arguments!={"--output":BLEND} or op.scene is not None):
        raise RuntimeError("Native frozen take operation deviated from pinned exporter")
    for name,source in expected["bytes"].items():
        if sha_file(staged["stage_dir"]/name)!=sha256(source).hexdigest():
            raise RuntimeError("Staged frozen take input differs from FilmIndex source")
    supervisor._validate(op)
    return True
